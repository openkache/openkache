struct CacheRow {
    /// A complete aligned PBFG row copied into ordinary owned memory.
    bytes: Box<[u8]>,
}

/// Set-indexed FIFO cache for 4 KiB PBFG rows.
///
/// Each cached row contains all SG-slot filters for one Set, so one index read
/// can prune every immutable candidate for that Set.
struct PbfgCache {
    rows: Vec<Option<CacheRow>>,
    capacity: usize,
    len: usize,
    fifo: VecDeque<usize>,
}

impl PbfgCache {
    fn new(set_count: usize, percent: usize) -> Self {
        let capacity = if percent == 0 {
            0
        } else {
            (set_count * percent).div_ceil(100).max(1)
        };
        Self {
            rows: (0..set_count).map(|_| None).collect(),
            capacity,
            len: 0,
            fifo: VecDeque::with_capacity(capacity),
        }
    }

    fn clear(&mut self) {
        for row in &mut self.rows {
            *row = None;
        }
        self.len = 0;
        self.fifo.clear();
    }

    fn contains(&self, set: usize) -> bool {
        self.rows[set].is_some()
    }

    /// Returns a PBFG row, loading one aligned page and evicting FIFO order on a miss.
    fn row<'a>(
        &'a mut self,
        file: &DirectFile,
        set: usize,
        stats: &mut IoStats,
    ) -> io::Result<&'a [u8]> {
        if self.rows[set].is_some() {
            stats.pbfg_cache_hits += 1;
            let row = self.rows[set].as_mut().unwrap();
            return Ok(&row.bytes);
        }

        let mut aligned = AlignedBytes::zeroed(PAGE_SIZE)?;
        file.read_exact_at(aligned.as_mut_slice(), (set * PAGE_SIZE) as u64)?;
        stats.index_read += PAGE_SIZE as u64;
        stats.pbfg_cache_misses += 1;

        if self.capacity == 0 {
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                "PBFG cache percentage must be non-zero for direct lookup",
            ));
        }
        if self.len == self.capacity {
            let victim = self.fifo.pop_front().expect("full PBFG cache has a victim");
            self.rows[victim] = None;
            self.len -= 1;
        }
        self.rows[set] = Some(CacheRow {
            bytes: aligned.as_slice().to_vec().into_boxed_slice(),
        });
        self.fifo.push_back(set);
        self.len += 1;
        Ok(&self.rows[set].as_ref().unwrap().bytes)
    }
}

/// Complete prototype state: two mutable SGs, a circular immutable data file,
/// a set-major PBFG file, and metadata needed for hot-object rescue.
struct Nemo {
    config: Config,
    data: DirectFile,
    index: DirectFile,
    /// Primary admission SG; this is the next immutable SG to flush.
    front: MutableSg,
    /// Overflow admission SG where P-flushing sacrifices the oldest records.
    back: MutableSg,
    next_generation: u64,
    /// Circular data-file slot that will be overwritten by the next flush.
    next_slot: usize,
    /// Logical generation currently occupying each physical SSD slot.
    slot_generation: Vec<Option<u64>>,
    /// In-memory filters built since the last complete PBFG-group write.
    current_filters: Vec<u8>,
    current_slot_valid: Vec<bool>,
    index_initialized: bool,
    pbfg_cache: PbfgCache,
    /// Optional one-bit-per-object hotness masks for the oldest SG window.
    access_masks: Vec<Option<Vec<u64>>>,
    sacrifices_since_flush: usize,
    data_flushes: u64,
    flush_metrics: Vec<FlushMetric>,
    io: IoStats,
}

impl Nemo {
    /// Creates sparse-sized data/index files and all aligned in-memory buffers.
    fn create(config: Config) -> Result<Self> {
        let data = DirectFile::create(&config.data_path, config.data_bytes()).map_err(|error| {
            format!(
                "cannot create O_DIRECT data file {}: {error}",
                config.data_path.display()
            )
        })?;
        let index = DirectFile::create(
            &config.index_path(),
            (config.set_count() * PAGE_SIZE) as u64,
        )
        .map_err(|error| {
            format!(
                "cannot create O_DIRECT PBFG file {}: {error}",
                config.index_path().display()
            )
        })?;
        Ok(Self {
            front: MutableSg::new(config.sg_size)?,
            back: MutableSg::new(config.sg_size)?,
            next_generation: 0,
            next_slot: 0,
            slot_generation: vec![None; config.sg_count],
            current_filters: vec![0; config.set_count() * config.sg_count * config.bloom_bytes],
            current_slot_valid: vec![false; config.sg_count],
            index_initialized: false,
            pbfg_cache: PbfgCache::new(config.set_count(), config.pbfg_cache_percent),
            access_masks: (0..config.sg_count).map(|_| None).collect(),
            sacrifices_since_flush: 0,
            data_flushes: 0,
            flush_metrics: Vec::new(),
            io: IoStats::default(),
            config,
            data,
            index,
        })
    }

    #[allow(dead_code)]
    fn set(&mut self, key: &[u8], value: &[u8]) -> Result<()> {
        let hash = Key::from(key).hashed_key().into_bytes();
        self.set_hashed(hash, value)
    }

    /// Admits a pre-hashed record using front → rear → sacrifice → rotate order.
    fn set_hashed(&mut self, hash: [u8; 32], value: &[u8]) -> Result<()> {
        if self.front.generation.is_none() {
            self.front.reset(self.next_generation);
            self.next_generation += 1;
        }
        if self.back.generation.is_none() {
            self.back.reset(self.next_generation);
            self.next_generation += 1;
        }
        let set = set_index(&hash, self.config.set_count());
        loop {
            if self.front.insert(set, &hash, value, true) {
                return Ok(());
            }
            if self
                .back
                .can_insert(set, value.len(), self.config.rear_fill_percent)
                && self.back.insert(set, &hash, value, true)
            {
                return Ok(());
            }

            // P-flushing trades the oldest rear records for enough local room.
            // Once the global sacrifice budget is consumed, rotate whole SGs
            // instead of repeatedly rewriting the same rear Set.
            if self.sacrifices_since_flush < self.config.pflush_threshold() {
                while !self
                    .back
                    .can_insert(set, value.len(), self.config.rear_fill_percent)
                {
                    let _removed = self
                        .back
                        .remove_oldest(set)
                        .ok_or("P-flushing could not sacrifice from the rear Set")?;
                    self.sacrifices_since_flush += 1;
                    self.io.pflush_sacrificed += 1;
                }
                if !self.back.insert(set, &hash, value, true) {
                    return Err("P-flushing did not create enough rear Set space".into());
                }
                return Ok(());
            }

            // Persist the front, promote the rear to front, and allocate a new
            // empty rear generation. The two mutable buffers are reused.
            self.flush_front()?;
            self.front.clear();
            std::mem::swap(&mut self.front, &mut self.back);
            self.back.reset(self.next_generation);
            self.next_generation += 1;
            self.sacrifices_since_flush = 0;
        }
    }

    #[allow(dead_code)]
    fn lookup(&mut self, key: &[u8]) -> Result<Option<Vec<u8>>> {
        let hash = Key::from(key).hashed_key().into_bytes();
        self.lookup_hashed(&hash)
    }

    /// Looks up a canonical hash from newest mutable data to oldest immutable data.
    fn lookup_hashed(&mut self, hash: &[u8; 32]) -> Result<Option<Vec<u8>>> {
        let set = set_index(hash, self.config.set_count());
        // Mutable buffers are newest and already resident, so probe them before
        // any index or data-file I/O.
        if let Some((value, _)) = self.back.find(set, hash) {
            return Ok(Some(value));
        }
        if let Some((value, _)) = self.front.find(set, hash) {
            return Ok(Some(value));
        }

        // Newest-to-oldest order makes an overwritten key resolve to its most
        // recent immutable value.
        let mut candidates: Vec<(u64, usize)> = self
            .slot_generation
            .iter()
            .enumerate()
            .filter_map(|(slot, generation)| generation.map(|generation| (generation, slot)))
            .collect();
        candidates.sort_unstable_by_key(|candidate| std::cmp::Reverse(candidate.0));

        // PBFG removes definite negatives; each positive costs one 4 KiB data read.
        for slot in self.pbfg_candidates(set, hash, &candidates)? {
            let mut page = AlignedBytes::zeroed(PAGE_SIZE)?;
            let offset = slot as u64 * self.config.sg_size as u64 + set as u64 * PAGE_SIZE as u64;
            self.data.read_exact_at(page.as_mut_slice(), offset)?;
            self.io.data_read += PAGE_SIZE as u64;
            if let Some((value, object_index)) = find_page(page.as_slice(), hash) {
                if let Some(mask) = &mut self.access_masks[slot]
                    && object_index < 64
                {
                    mask[set] |= 1u64 << object_index;
                }
                return Ok(Some(value));
            }
            self.io.false_positive_reads += 1;
        }
        Ok(None)
    }

    /// Rescues hot objects, overwrites one circular slot, and advances index state.
    fn flush_front(&mut self) -> Result<()> {
        let slot = self.next_slot;
        // Hot objects from the victim slot are appended without counting them as
        // new logical writes, keeping ALWA denominators honest.
        let rescued = self.collect_hot(slot)?;
        let mut hot_objects = 0u64;
        for (hash, value) in rescued {
            let set = set_index(&hash, self.config.set_count());
            if self.front.insert(set, &hash, &value, false) {
                hot_objects += 1;
                self.io.hot_reinserted += 1;
            } else {
                self.io.hot_dropped += 1;
            }
        }
        let generation = self.front.generation.ok_or("cannot flush an empty SG")?;
        self.flush_metrics.push(FlushMetric {
            packed_bytes: self.front.packed_object_bytes(),
            new_logical_bytes: self.front.new_logical_bytes,
            new_objects: self.front.new_objects,
            sacrificed_objects: self.front.sacrificed_objects,
            hot_objects,
        });

        // A complete SG write is the atomic physical unit measured by this prototype.
        self.data.write_all_at(
            self.front.bytes.as_slice(),
            slot as u64 * self.config.sg_size as u64,
        )?;
        self.io.data_written += self.config.sg_size as u64;
        self.build_slot_filters(slot);
        self.slot_generation[slot] = Some(generation);
        self.next_slot = (slot + 1) % self.config.sg_count;
        self.data_flushes += 1;
        self.refresh_access_masks();

        if self.current_slot_valid.iter().all(|valid| *valid) {
            self.flush_pbfg_group()?;
        }
        let cooling_period = (self.config.sg_count * 10).div_ceil(100).max(1) as u64;
        if self.data_flushes.is_multiple_of(cooling_period) {
            self.cool_access_masks();
        }
        Ok(())
    }

    #[allow(dead_code)]
    fn finish(&mut self) -> Result<()> {
        if self.front.generation.is_some() {
            self.flush_front()?;
            self.front.clear();
        }
        if self.back.generation.is_some() {
            std::mem::swap(&mut self.front, &mut self.back);
            self.flush_front()?;
            self.front.clear();
        }
        if self.current_slot_valid.iter().any(|valid| *valid) {
            self.flush_pbfg_group()?;
        }
        self.data.sync()?;
        self.index.sync()?;
        Ok(())
    }

    fn sync_files(&self) -> Result<()> {
        self.data.sync()?;
        self.index.sync()?;
        Ok(())
    }

    /// Builds all Set filters for one freshly written SG slot in set-major order.
    fn build_slot_filters(&mut self, slot: usize) {
        let stride = self.config.sg_count * self.config.bloom_bytes;
        for set in 0..self.config.set_count() {
            let filter_start = set * stride + slot * self.config.bloom_bytes;
            let filter_end = filter_start + self.config.bloom_bytes;
            let filter = &mut self.current_filters[filter_start..filter_end];
            filter.fill(0);
            let page_start = set * PAGE_SIZE;
            let page = &self.front.bytes.as_slice()[page_start..page_start + PAGE_SIZE];
            for (hash, _) in records(page) {
                bloom_insert(filter, self.config.bloom_hashes, &hash);
            }
        }
        self.current_slot_valid[slot] = true;
    }

    /// Persists a full set-major PBFG image, merging untouched slots if partial.
    fn flush_pbfg_group(&mut self) -> Result<()> {
        let complete_group = self.current_slot_valid.iter().all(|valid| *valid);
        let old_index = if self.index_initialized && !complete_group {
            let mut old = AlignedBytes::zeroed(self.config.set_count() * PAGE_SIZE)?;
            self.index.read_exact_at(old.as_mut_slice(), 0)?;
            self.io.index_read += old.len as u64;
            Some(old)
        } else {
            None
        };
        let mut output = AlignedBytes::zeroed(self.config.set_count() * PAGE_SIZE)?;
        let filter_stride = self.config.sg_count * self.config.bloom_bytes;
        for set in 0..self.config.set_count() {
            let page = &mut output.as_mut_slice()[set * PAGE_SIZE..(set + 1) * PAGE_SIZE];
            put_u32(page, 0, PBFG_MAGIC);
            put_u16(page, 4, self.config.sg_count as u16);
            put_u16(page, 6, self.config.bloom_bytes as u16);
            put_u32(page, 8, self.config.bloom_hashes);
            let source = &self.current_filters[set * filter_stride..(set + 1) * filter_stride];
            page[PBFG_HEADER..PBFG_HEADER + filter_stride].copy_from_slice(source);
            if let Some(old) = &old_index {
                let old_page = &old.as_slice()[set * PAGE_SIZE..(set + 1) * PAGE_SIZE];
                for slot in 0..self.config.sg_count {
                    if !self.current_slot_valid[slot] {
                        let start = PBFG_HEADER + slot * self.config.bloom_bytes;
                        page[start..start + self.config.bloom_bytes]
                            .copy_from_slice(&old_page[start..start + self.config.bloom_bytes]);
                    }
                }
            }
        }
        self.index.write_all_at(output.as_slice(), 0)?;
        self.io.index_written += output.len as u64;
        self.index_initialized = true;
        self.current_filters.fill(0);
        self.current_slot_valid.fill(false);
        self.pbfg_cache.clear();
        Ok(())
    }

    /// Returns only SG slots whose per-Set Bloom filters may contain `hash`.
    fn pbfg_candidates(
        &mut self,
        set: usize,
        hash: &[u8; 32],
        candidates: &[(u64, usize)],
    ) -> Result<Vec<usize>> {
        let stride = self.config.sg_count * self.config.bloom_bytes;
        let positions: Vec<usize> =
            bloom_positions(self.config.bloom_bytes * 8, self.config.bloom_hashes, hash).collect();
        // Filters built after the last PBFG flush remain in RAM; older slot
        // filters share one cached/on-disk row for this Set.
        let needs_disk_row = candidates
            .iter()
            .any(|(_, slot)| !self.current_slot_valid[*slot]);
        let disk_row = if needs_disk_row {
            let row = self.pbfg_cache.row(&self.index, set, &mut self.io)?;
            if get_u32(row, 0) != PBFG_MAGIC {
                return Err("invalid PBFG row magic".into());
            }
            Some(row)
        } else {
            None
        };

        let compute_started = Instant::now();
        let mut positive = Vec::new();
        for (_, slot) in candidates {
            let filter = if self.current_slot_valid[*slot] {
                let start = set * stride + *slot * self.config.bloom_bytes;
                &self.current_filters[start..start + self.config.bloom_bytes]
            } else {
                let row = disk_row.expect("disk row is loaded for persisted filters");
                let start = PBFG_HEADER + *slot * self.config.bloom_bytes;
                &row[start..start + self.config.bloom_bytes]
            };
            self.io.bloom_filter_checks += 1;
            if bloom_contains_positions(filter, &positions) {
                self.io.bloom_filter_positives += 1;
                positive.push(*slot);
            }
        }
        self.io.pbfg_compute_ns += compute_started.elapsed().as_nanos();
        self.io.pbfg_queries += 1;
        Ok(positive)
    }

    /// Assigns hotness masks to the oldest configured percentage of occupied slots.
    fn refresh_access_masks(&mut self) {
        let mut occupied: Vec<(u64, usize)> = self
            .slot_generation
            .iter()
            .enumerate()
            .filter_map(|(slot, generation)| generation.map(|generation| (generation, slot)))
            .collect();
        occupied.sort_unstable();
        let tracked = (occupied.len() * self.config.hot_window_percent).div_ceil(100);
        let mut should_track = vec![false; self.config.sg_count];
        for (_, slot) in occupied.into_iter().take(tracked) {
            should_track[slot] = true;
        }
        for (slot, track) in should_track.into_iter().enumerate() {
            match (track, self.access_masks[slot].is_some()) {
                (true, false) => {
                    self.access_masks[slot] = Some(vec![0; self.config.set_count()]);
                }
                (false, true) => self.access_masks[slot] = None,
                _ => {}
            }
        }
    }

    /// Clears hot bits whose PBFG rows are no longer resident, bounding stale heat.
    fn cool_access_masks(&mut self) {
        for mask in self.access_masks.iter_mut().flatten() {
            for (set, bits) in mask.iter_mut().enumerate() {
                if !self.pbfg_cache.contains(set) {
                    *bits = 0;
                }
            }
        }
        self.io.cooling_passes += 1;
    }

    /// Reads marked objects from the slot about to be overwritten for reinsertion.
    fn collect_hot(&mut self, slot: usize) -> Result<Vec<([u8; 32], Vec<u8>)>> {
        let Some(mask) = self.access_masks[slot].take() else {
            return Ok(Vec::new());
        };
        let mut rescued = Vec::new();
        for (set, bits) in mask.into_iter().enumerate() {
            if bits == 0 || !self.pbfg_cache.contains(set) {
                continue;
            }
            let mut page = AlignedBytes::zeroed(PAGE_SIZE)?;
            let offset = slot as u64 * self.config.sg_size as u64 + set as u64 * PAGE_SIZE as u64;
            self.data.read_exact_at(page.as_mut_slice(), offset)?;
            self.io.data_read += PAGE_SIZE as u64;
            for (index, (hash, value)) in records(page.as_slice()).into_iter().enumerate() {
                if index < 64 && bits & (1u64 << index) != 0 {
                    rescued.push((hash, value));
                }
            }
        }
        Ok(rescued)
    }
}

/// Appends `[32-byte hash][u16 value length][value]` to a Set page.
pub(crate) fn insert_page(page: &mut [u8], hash: &[u8; 32], value: &[u8]) -> bool {
    let used = get_u16(page, 12) as usize;
    let required = ENTRY_HEADER + value.len();
    if used + required > page.len() {
        return false;
    }
    page[used..used + 32].copy_from_slice(hash);
    put_u16(page, used + 32, value.len() as u16);
    page[used + ENTRY_HEADER..used + required].copy_from_slice(value);
    put_u16(page, 12, (used + required) as u16);
    let count = get_u16(page, 14);
    put_u16(page, 14, count + 1);
    true
}

pub(crate) fn find_page(page: &[u8], wanted: &[u8; 32]) -> Option<(Vec<u8>, usize)> {
    records(page)
        .into_iter()
        .enumerate()
        .find_map(|(index, (hash, value))| (hash == *wanted).then_some((value, index)))
}

/// Decodes valid records defensively, stopping at the first truncated entry.
fn records(page: &[u8]) -> Vec<([u8; 32], Vec<u8>)> {
    if page.len() != PAGE_SIZE || get_u32(page, 0) != PAGE_MAGIC {
        return Vec::new();
    }
    let used = (get_u16(page, 12) as usize).min(PAGE_SIZE);
    let count = get_u16(page, 14) as usize;
    let mut offset = PAGE_HEADER;
    let mut result = Vec::with_capacity(count);
    for _ in 0..count {
        if offset + ENTRY_HEADER > used {
            break;
        }
        let mut hash = [0u8; 32];
        hash.copy_from_slice(&page[offset..offset + 32]);
        let value_len = get_u16(page, offset + 32) as usize;
        let end = offset + ENTRY_HEADER + value_len;
        if end > used {
            break;
        }
        result.push((hash, page[offset + ENTRY_HEADER..end].to_vec()));
        offset = end;
    }
    result
}

/// Sets every deterministic Bloom position derived from a canonical hash.
pub(crate) fn bloom_insert(filter: &mut [u8], hashes: u32, key: &[u8; 32]) {
    for bit in bloom_positions(filter.len() * 8, hashes, key) {
        filter[bit / 8] |= 1 << (bit % 8);
    }
}

fn bloom_contains_positions(filter: &[u8], positions: &[usize]) -> bool {
    positions
        .iter()
        .all(|bit| filter[*bit / 8] & (1 << (*bit % 8)) != 0)
}

/// Expands four mixed 64-bit lanes into `hashes` independent-looking positions.
/// The benchmark reuses these positions across all SG filters in a PBFG row.
pub(crate) fn bloom_positions(
    bits: usize,
    hashes: u32,
    key: &[u8; 32],
) -> impl Iterator<Item = usize> + '_ {
    let first = u64::from_le_bytes(key[0..8].try_into().unwrap());
    let second = u64::from_le_bytes(key[8..16].try_into().unwrap()).rotate_left(17);
    let third = u64::from_le_bytes(key[16..24].try_into().unwrap()).rotate_left(31);
    let fourth = u64::from_le_bytes(key[24..32].try_into().unwrap()).rotate_left(47);
    let seed = first ^ second ^ third ^ fourth;
    (0..hashes).map(move |index| {
        splitmix64(seed ^ (index as u64).wrapping_mul(0xd6e8_feb8_6659_fd93)) as usize % bits
    })
}

/// Maps the first hash lane to a Set number.
pub(crate) fn set_index(hash: &[u8; 32], set_count: usize) -> usize {
    u64::from_le_bytes(hash[0..8].try_into().unwrap()) as usize % set_count
}

/// Generates repeatable benchmark hashes while forcing each key into `set`.
pub(crate) fn benchmark_hash(
    generation: usize,
    set: usize,
    object: usize,
    set_count: usize,
) -> [u8; 32] {
    let sequence = ((generation as u64) << 40) ^ ((set as u64) << 16) ^ object as u64;
    let mut hash = [0u8; 32];
    let mut first = splitmix64(sequence ^ 0x243f_6a88_85a3_08d3);
    if set_count.is_power_of_two() {
        first = (first & !((set_count - 1) as u64)) | set as u64;
    } else {
        first = first - first % set_count as u64 + set as u64;
    }
    hash[0..8].copy_from_slice(&first.to_le_bytes());
    hash[8..16].copy_from_slice(&splitmix64(sequence ^ 0x1319_8a2e_0370_7344).to_le_bytes());
    hash[16..24].copy_from_slice(&splitmix64(sequence ^ 0xa409_3822_299f_31d0).to_le_bytes());
    hash[24..32].copy_from_slice(&splitmix64(sequence ^ 0x082e_fa98_ec4e_6c89).to_le_bytes());
    hash
}

fn splitmix64(mut value: u64) -> u64 {
    value = value.wrapping_add(0x9e37_79b9_7f4a_7c15);
    value = (value ^ (value >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
    value = (value ^ (value >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
    value ^ (value >> 31)
}

pub(crate) fn put_u16(data: &mut [u8], offset: usize, value: u16) {
    data[offset..offset + 2].copy_from_slice(&value.to_le_bytes());
}

fn get_u16(data: &[u8], offset: usize) -> u16 {
    u16::from_le_bytes(data[offset..offset + 2].try_into().unwrap())
}

pub(crate) fn put_u32(data: &mut [u8], offset: usize, value: u32) {
    data[offset..offset + 4].copy_from_slice(&value.to_le_bytes());
}

fn get_u32(data: &[u8], offset: usize) -> u32 {
    u32::from_le_bytes(data[offset..offset + 4].try_into().unwrap())
}

fn put_u64(data: &mut [u8], offset: usize, value: u64) {
    data[offset..offset + 8].copy_from_slice(&value.to_le_bytes());
}

fn mib(bytes: u64) -> f64 {
    bytes as f64 / (1024.0 * 1024.0)
}

fn throughput(bytes: u64, duration: Duration) -> f64 {
    mib(bytes) / duration.as_secs_f64()
}

