struct AlignedBytes {
    /// Page-aligned allocation required by Linux `O_DIRECT`.
    ptr: *mut u8,
    len: usize,
}

impl AlignedBytes {
    /// Allocates zeroed memory whose address and length both satisfy direct I/O.
    fn zeroed(len: usize) -> io::Result<Self> {
        if len == 0 || !len.is_multiple_of(PAGE_SIZE) {
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                "direct-I/O buffer length must be a non-zero multiple of 4 KiB",
            ));
        }
        let mut raw = std::ptr::null_mut();
        let status = unsafe { libc::posix_memalign(&mut raw, PAGE_SIZE, len) };
        if status != 0 {
            return Err(io::Error::from_raw_os_error(status));
        }
        // SAFETY: `posix_memalign` returned a non-null allocation of `len`
        // writable bytes when its status is zero.
        unsafe { std::ptr::write_bytes(raw, 0, len) };
        Ok(Self {
            ptr: raw.cast(),
            len,
        })
    }

    fn as_slice(&self) -> &[u8] {
        // SAFETY: the allocation remains owned by `self` for the returned
        // borrow and was created with exactly `self.len` bytes.
        unsafe { std::slice::from_raw_parts(self.ptr, self.len) }
    }

    fn as_mut_slice(&mut self) -> &mut [u8] {
        // SAFETY: `&mut self` guarantees exclusive access to the allocation.
        unsafe { std::slice::from_raw_parts_mut(self.ptr, self.len) }
    }
}

impl Drop for AlignedBytes {
    fn drop(&mut self) {
        // SAFETY: `ptr` came from `posix_memalign` and is released exactly once.
        unsafe { libc::free(self.ptr.cast()) };
    }
}

/// File wrapper that keeps every benchmark data/index operation on `O_DIRECT`.
struct DirectFile {
    file: File,
}

impl DirectFile {
    fn create(path: &Path, len: u64) -> io::Result<Self> {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        let file = OpenOptions::new()
            .read(true)
            .write(true)
            .create(true)
            .truncate(true)
            .custom_flags(libc::O_DIRECT | libc::O_CLOEXEC)
            .open(path)?;
        file.set_len(len)?;
        Ok(Self { file })
    }

    fn write_all_at(&self, data: &[u8], offset: u64) -> io::Result<()> {
        direct_io(
            self.file.as_raw_fd(),
            data.as_ptr().cast_mut(),
            data.len(),
            offset,
            true,
        )
    }

    fn read_exact_at(&self, data: &mut [u8], offset: u64) -> io::Result<()> {
        direct_io(
            self.file.as_raw_fd(),
            data.as_mut_ptr(),
            data.len(),
            offset,
            false,
        )
    }

    fn sync(&self) -> io::Result<()> {
        self.file.sync_data()
    }
}

/// Completes a positional direct-I/O request, retrying interrupts and rejecting
/// partial transfers that would break the alignment of the next request.
fn direct_io(fd: i32, ptr: *mut u8, len: usize, offset: u64, write: bool) -> io::Result<()> {
    if !len.is_multiple_of(PAGE_SIZE) || !offset.is_multiple_of(PAGE_SIZE as u64) {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "O_DIRECT length and offset must be 4 KiB aligned",
        ));
    }
    let mut completed = 0usize;
    while completed < len {
        // SAFETY: callers provide a live allocation of `len` bytes. Both the
        // allocation and file offset are page aligned, and `completed` never
        // advances past the allocation.
        let result = unsafe {
            if write {
                libc::pwrite(
                    fd,
                    ptr.add(completed).cast(),
                    len - completed,
                    (offset + completed as u64) as libc::off_t,
                )
            } else {
                libc::pread(
                    fd,
                    ptr.add(completed).cast(),
                    len - completed,
                    (offset + completed as u64) as libc::off_t,
                )
            }
        };
        if result < 0 {
            let error = io::Error::last_os_error();
            if error.kind() == io::ErrorKind::Interrupted {
                continue;
            }
            return Err(error);
        }
        if result == 0 {
            return Err(io::Error::new(
                io::ErrorKind::UnexpectedEof,
                "short direct I/O",
            ));
        }
        let transferred = result as usize;
        if completed + transferred < len && !transferred.is_multiple_of(PAGE_SIZE) {
            return Err(io::Error::new(
                io::ErrorKind::WriteZero,
                "unaligned partial direct I/O",
            ));
        }
        completed += transferred;
    }
    Ok(())
}

/// One in-memory SG arranged as `set_count` independent 4 KiB append-only Sets.
pub(crate) struct MutableSg {
    bytes: AlignedBytes,
    generation: Option<u64>,
    new_logical_bytes: u64,
    new_objects: u64,
    pub(crate) sacrificed_objects: u64,
}

impl MutableSg {
    pub(crate) fn new(size: usize) -> io::Result<Self> {
        Ok(Self {
            bytes: AlignedBytes::zeroed(size)?,
            generation: None,
            new_logical_bytes: 0,
            new_objects: 0,
            sacrificed_objects: 0,
        })
    }

    /// Starts a new logical generation and initializes every Set header.
    pub(crate) fn reset(&mut self, generation: u64) {
        self.bytes.as_mut_slice().fill(0);
        self.generation = Some(generation);
        self.new_logical_bytes = 0;
        self.new_objects = 0;
        self.sacrificed_objects = 0;
        let (pages, remainder) = self.bytes.as_mut_slice().as_chunks_mut::<PAGE_SIZE>();
        debug_assert!(remainder.is_empty());
        for page in pages {
            put_u32(page, 0, PAGE_MAGIC);
            put_u64(page, 4, generation);
            put_u16(page, 12, PAGE_HEADER as u16);
            put_u16(page, 14, 0);
        }
    }

    fn clear(&mut self) {
        self.generation = None;
    }

    /// Appends a record to one Set and optionally charges it as new logical data.
    pub(crate) fn insert(
        &mut self,
        set: usize,
        hash: &[u8; 32],
        value: &[u8],
        count_as_new: bool,
    ) -> bool {
        let start = set * PAGE_SIZE;
        let page = &mut self.bytes.as_mut_slice()[start..start + PAGE_SIZE];
        let inserted = insert_page(page, hash, value);
        if inserted && count_as_new {
            self.new_logical_bytes += (hash.len() + value.len()) as u64;
            self.new_objects += 1;
        }
        inserted
    }

    /// Checks rear-Set admission against a configured headroom boundary.
    fn can_insert(&self, set: usize, value_len: usize, fill_percent: usize) -> bool {
        let start = set * PAGE_SIZE;
        let page = &self.bytes.as_slice()[start..start + PAGE_SIZE];
        let used = get_u16(page, 12) as usize;
        let data_capacity = PAGE_SIZE - PAGE_HEADER;
        let limit = PAGE_HEADER + data_capacity * fill_percent / 100;
        used + ENTRY_HEADER + value_len <= limit
    }

    /// Sacrifices the first (oldest) record and compacts the remaining Set bytes.
    pub(crate) fn remove_oldest(&mut self, set: usize) -> Option<([u8; 32], Vec<u8>)> {
        let start = set * PAGE_SIZE;
        let page = &mut self.bytes.as_mut_slice()[start..start + PAGE_SIZE];
        let removed = records(page).into_iter().next()?;
        let value_len = get_u16(page, PAGE_HEADER + 32) as usize;
        let record_len = ENTRY_HEADER + value_len;
        let used = get_u16(page, 12) as usize;
        page.copy_within(PAGE_HEADER + record_len..used, PAGE_HEADER);
        page[used - record_len..used].fill(0);
        put_u16(page, 12, (used - record_len) as u16);
        put_u16(page, 14, get_u16(page, 14) - 1);
        self.sacrificed_objects += 1;
        Some(removed)
    }

    fn packed_object_bytes(&self) -> u64 {
        if self.generation.is_none() {
            return 0;
        }
        self.bytes
            .as_slice()
            .as_chunks::<PAGE_SIZE>()
            .0
            .iter()
            .map(|page| get_u16(page, 12) as u64 - PAGE_HEADER as u64)
            .sum()
    }

    pub(crate) fn find(&self, set: usize, hash: &[u8; 32]) -> Option<(Vec<u8>, usize)> {
        self.generation?;
        let start = set * PAGE_SIZE;
        find_page(&self.bytes.as_slice()[start..start + PAGE_SIZE], hash)
    }
}

