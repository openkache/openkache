//! Small, direct-I/O Nemo prototype and development benchmark.
//!
//! The default geometry is intentionally laptop-sized: 4 KiB sets, 16 MiB
//! segment groups (SGs), and a 32-SG FIFO (512 MiB of data).  Two mutable SGs
//! live in memory. Immutable SGs and set-level PBFG rows are accessed with
//! `O_DIRECT`, so benchmark reads and writes bypass the Linux page cache.
//!
//! The prototype follows this data path:
//! 1. Hash each key once and map its first 64 bits to a 4 KiB Set.
//! 2. Admit new records to the in-memory front SG, then the rear SG.
//! 3. When both Sets are full, sacrifice the oldest rear records until the
//!    global P-flushing threshold requests an SG rotation.
//! 4. Flush one immutable SG into a circular on-disk slot.
//! 5. Build one Bloom filter per `(Set, SG slot)` and persist all filters for a
//!    Set together in one 4 KiB PBFG row.
//! 6. On lookup, check mutable SGs first, use PBFG to prune immutable SGs, and
//!    issue a direct 4 KiB read only for positive candidates.
//! 7. Track reads in the oldest SG window so hot objects can be rescued before
//!    their circular slots are overwritten.

use std::collections::VecDeque;
use std::error::Error;
use std::fs::{File, OpenOptions};
use std::io;
use std::os::fd::AsRawFd;
use std::os::unix::fs::OpenOptionsExt;
use std::path::{Path, PathBuf};
use std::time::{Duration, Instant};

use openkache::Key;

/// Direct-I/O alignment and the physical size of one logical Set.
pub(crate) const PAGE_SIZE: usize = 4096;
/// Little-endian `NEMO` marker stored at the start of every data Set.
pub(crate) const PAGE_MAGIC: u32 = 0x4e45_4d4f;
/// Little-endian `PBFG` marker stored at the start of every index row.
const PBFG_MAGIC: u32 = 0x5042_4647;
/// Set header: magic (4), generation (8), used bytes (2), record count (2).
pub(crate) const PAGE_HEADER: usize = 16;
/// Record header: canonical SHA-256 key (32) followed by value length (2).
const ENTRY_HEADER: usize = 34;
/// PBFG row header: magic, geometry, and Bloom hash-count metadata.
const PBFG_HEADER: usize = 16;
/// Paper geometry: 275,712 Sets with 40 objects per Set in one SG.
const REFERENCE_OBJECTS_PER_SG: usize = 275_712 * 40;
/// P-flushing threshold evaluated for the paper geometry.
const REFERENCE_PFLUSH_THRESHOLD: usize = 4_096;

type Result<T> = std::result::Result<T, Box<dyn Error>>;

#[derive(Clone, Debug)]
/// Runtime geometry and workload parameters shared by every benchmark phase.
struct Config {
    /// Base path for immutable SG data; PBFG uses the same path plus `.pbfg`.
    data_path: PathBuf,
    /// Bytes per segment group. Must be a multiple of one Set page.
    sg_size: usize,
    /// Number of immutable slots in the circular SSD FIFO.
    sg_count: usize,
    /// Fixed payload size generated by the benchmark loader.
    value_bytes: usize,
    /// Bloom-filter bytes allocated per `(Set, SG slot)` pair.
    bloom_bytes: usize,
    bloom_hashes: u32,
    /// Percentage of set-level PBFG rows retained in the in-memory FIFO cache.
    pbfg_cache_percent: usize,
    /// Percentage of the oldest occupied SG slots tracked for hot reads.
    hot_window_percent: usize,
    lookup_count: usize,
    hit_percent: usize,
    zipf_alpha: f64,
    /// Explicit rear-Set sacrifice limit; `None` scales the paper threshold.
    pflush_threshold_override: Option<usize>,
    /// Admission ceiling that leaves headroom in each rear Set.
    rear_fill_percent: usize,
    /// Number of post-fill SG rotations used to measure steady-state WA.
    steady_flushes: usize,
    /// Insert interval between hotness-generating reads; zero disables reads.
    steady_read_every: usize,
    keep_files: bool,
}

